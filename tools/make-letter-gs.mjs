// Turns private/letter.md into private/Letter.gs (a seedLetters_() function for Apps Script).
// The letter text is never printed or written anywhere except the output file.
// Usage: npm run letter:gs [-- --in <path> --out <path>]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? resolve(args[i + 1]) : fallback;
};
const input = arg('--in', resolve(root, 'private/letter.md'));
const output = arg('--out', resolve(root, 'private/Letter.gs'));

if (!existsSync(input)) {
  console.error(`No letter found at ${relative(process.cwd(), input) || input}.`);
  console.error('Write the letter there first (it stays private and out of git), then run: npm run letter:gs');
  process.exit(1);
}

const body = readFileSync(input, 'utf8');
const letter = {
  letter_id: 'LETTER-PILLOW-0001',
  title: 'A note on your pillow',
  from: 'nirsh',
  to: 'shady',
  unlock_rule: 'always',
  written_at: '2026-09-19',
  read_at: '',
  created_at: '2026-09-19T20:00:00.000Z',
  updated_at: '2026-09-19T20:00:00.000Z',
};

const source = `// Generated by tools/make-letter-gs.mjs. PRIVATE: never commit or share this file.
// Paste it into the Apps Script editor as a file named "Letter", then run setup() once.

/** Adds the pillow letter to the Letters tab once. Running it again changes nothing. */
function seedLetters_() {
  var letter = ${JSON.stringify(letter, null, 2).replace(/\n/g, '\n  ')};
  letter.body_md = ${JSON.stringify(body)};
  if (getRowById_('Letters', 'letter_id', letter.letter_id)) return 'Letter already in the Sheet';
  upsertRowById_('Letters', 'letter_id', letter);
  return 'Letter added';
}
`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, source, 'utf8');
console.log(`Wrote ${relative(process.cwd(), output) || output} (letter of ${body.length} characters).`);
